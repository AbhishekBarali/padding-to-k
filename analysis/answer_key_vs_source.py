#!/usr/bin/env python3
"""answer_key_vs_source.py: the cleaned answer lists against the source datasets' own counts.

    python analysis/answer_key_vs_source.py

Every study document (pilot and full, 558) has two counts: the one its source dataset's annotators gave
(`n_original` in data/documents.jsonl; `n_before` in data/cleanup/changes_reviews_no_text.csv for the
review set, whose text is not in the repository) and the one in the cleaned answer list (`n`). This
script compares them per set: how often they are equal, and in which direction they differ.

It then puts both counts next to the blind check: for every blind-check document, does each author's
count match the annotators' count or the cleaned count?

data/cleanup/REPORT.md already lists how counts moved, but over all 1,446 checked documents (dropped and
reserve ones included) and without an agreement rate; this script restricts it to the 558 study documents.

Writes analysis/answer_key/REPORT.md and analysis/answer_key/differing_documents.csv (every study
document whose two counts differ, with the cleanup's rule and reason).
"""
import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "analysis/answer_key"
STUDY = {"pilot", "full"}
SET_ORDER = ["meetings", "emails", "receipts", "job_posts", "clinical", "reviews",
             "job_posts_knowledge", "wiki_people", "novel_quotes"]
BLIND = [
    (1, ROOT / "data/blind/blind_sheet_fresh_A.csv", ROOT / "data/blind/blind_sheet_fresh_B.csv"),
    (2, ROOT / "analysis/blind/blind_sheet_round2_A_filled.csv", ROOT / "analysis/blind/blind_sheet_round2_B_filled.csv"),
]
CHANGED = {"meetings", "emails", "job_posts", "job_posts_knowledge", "clinical"}  # rule 3's pool, as blind_rule3.py


def jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def study_documents():
    """(doc_id, set, split, n_source, n_clean, status, rules, reason) for the 558 study documents."""
    rows = []
    for d in jsonl(ROOT / "data/documents.jsonl"):
        if d["split"] in STUDY:
            c = d.get("cleanup") or {}
            rows.append((d["doc_id"], d["set"], d["split"], d["n_original"], d["n"], c.get("status", ""),
                         " ".join(c.get("rules") or []), c.get("reason", "")))
    # Review set: text not committed; counts come from the restricted id list and the text-free change list.
    restricted = {r["doc_id"]: r for r in jsonl(ROOT / "data/restricted_ids.jsonl")}
    with open(ROOT / "data/cleanup/changes_reviews_no_text.csv", newline="", encoding="utf-8") as f:
        changes = {r["doc_id"]: r for r in csv.DictReader(f)}
    decisions = {r["doc_id"]: r for r in jsonl(ROOT / "data/cleanup/decisions.jsonl")}
    for i, r in restricted.items():
        if r["split"] not in STUDY:
            continue
        dec = decisions[i]
        if i in changes:
            n_src, n_cl = int(changes[i]["n_before"]), int(changes[i]["n_after"])
            if n_cl != r["n"]:
                raise SystemExit(f"{i}: n_after {n_cl} differs from restricted_ids n {r['n']}")
        elif dec["status"] == "ok" and not dec.get("changes"):
            n_src = n_cl = r["n"]  # unchanged and never moved, so not listed in the change file
        else:
            raise SystemExit(f"{i}: no count before cleanup on record")
        rows.append((i, "reviews", r["split"], n_src, n_cl, dec["status"], " ".join(dec.get("rules") or []),
                     dec.get("reason", "")))
    return rows


def read_sheet(path):
    with open(path, newline="", encoding="utf-8-sig") as f:
        return {r["doc_id"]: r for r in csv.DictReader(f)}


def pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "-"


def main():
    rows = study_documents()
    if len(rows) != 558:
        raise SystemExit(f"expected 558 study documents, found {len(rows)}")
    OUT.mkdir(parents=True, exist_ok=True)

    per = defaultdict(lambda: {"docs": 0, "same": 0, "up": 0, "down": 0, "sum": 0, "fixed": 0, "fixed_same": 0})
    for _, s, split, ns, nc, status, _, _ in rows:
        for key in (s, "all", f"pilot:{s}" if split == "pilot" else None):
            if key is None:
                continue
            t = per[key]
            t["docs"] += 1
            t["same"] += ns == nc
            t["up"] += nc > ns
            t["down"] += nc < ns
            t["sum"] += nc - ns
            t["fixed"] += status == "fixed"
            t["fixed_same"] += status == "fixed" and ns == nc

    lines = ["# Answer lists against the source datasets' counts", "",
             "Generated by `python analysis/answer_key_vs_source.py`; do not edit.", "",
             "Study documents only (pilot and full, 558). Source count: the count the dataset's own annotators gave. "
             "Cleaned count: the frozen answer list (`prereg-v1`). Higher / lower: the cleaned count is higher or "
             "lower than the source count. Fixed, same count: lists the cleanup changed (items removed, added, split "
             "or re-cut) whose count did not move.", "",
             "| Set | documents | same count | cleaned higher | cleaned lower | mean change (cleaned minus source) | fixed lists | fixed, same count |",
             "|---|---|---|---|---|---|---|---|"]
    for s in SET_ORDER + ["all"]:
        t = per[s]
        lines.append(f"| {s} | {t['docs']} | {t['same']} ({pct(t['same'], t['docs'])}) | {t['up']} | {t['down']} | "
                     f"{t['sum'] / t['docs']:+.2f} | {t['fixed']} | {t['fixed_same']} |")
    lines += ["", "Pilot documents only:", "", "| Set | documents | same count | cleaned higher | cleaned lower | mean change |",
              "|---|---|---|---|---|---|"]
    for s in ("meetings", "emails"):
        t = per[f"pilot:{s}"]
        lines.append(f"| {s} | {t['docs']} | {t['same']} ({pct(t['same'], t['docs'])}) | {t['up']} | {t['down']} | {t['sum'] / t['docs']:+.2f} |")

    # Size of the differences.
    gaps = defaultdict(int)
    for _, _, _, ns, nc, _, _, _ in rows:
        if ns != nc:
            gaps[abs(nc - ns)] += 1
    lines += ["", "Size of the differences (all sets): " +
              ", ".join(f"{g} item{'s' if g > 1 else ''}: {c} documents" for g, c in sorted(gaps.items())) + "."]

    # Blind check: does each author agree with the source count or the cleaned count?
    clean = {r[0]: r for r in rows}
    reserve_docs = {d["doc_id"]: d for d in jsonl(ROOT / "data/documents.jsonl")}
    bl = defaultdict(lambda: {"docs": 0, "A_src": 0, "A_cl": 0, "B_src": 0, "B_cl": 0, "differ": 0,
                              "dA_src": 0, "dA_cl": 0, "dB_src": 0, "dB_cl": 0})
    for rnd, pa, pb in BLIND:
        a, b = read_sheet(pa), read_sheet(pb)
        for i in a:
            if i in clean:
                ns, nc = clean[i][3], clean[i][4]
            else:  # a blind-check document that later left the study (e.g. the dropped jbk-e5e5cd)
                d = reserve_docs[i]
                ns, nc = d["n_original"], d["n"]
                if d["split"] not in STUDY:
                    continue
            na, nb = int(a[i]["n_found"]), int(b[i]["n_found"])
            keys = [f"round {rnd}", "both rounds"]
            if rnd == 2 or a[i]["set"] not in CHANGED:
                keys.append("rule-3 pool (40)")
            for key in keys:
                t = bl[key]
                t["docs"] += 1
                t["A_src"] += na == ns
                t["A_cl"] += na == nc
                t["B_src"] += nb == ns
                t["B_cl"] += nb == nc
                t["differ"] += ns != nc
                if ns != nc:
                    t["dA_src"] += na == ns
                    t["dA_cl"] += na == nc
                    t["dB_src"] += nb == ns
                    t["dB_cl"] += nb == nc
    lines += ["", "## The blind check against both counts", "",
              "Each author's blind count (`data/blind/`, `analysis/blind/`) compared with the source count and with the "
              "cleaned count. Documents that left the study after round 1 are not counted. Round 1 used the earlier "
              "definitions, and its cleaned count for eml-053cb0 is the one the round-1 settlement set, so round 1 is not "
              "fully independent of the cleaned list. The last four columns count only the documents whose two counts differ.", "",
              "| Documents | n | A = source | A = cleaned | B = source | B = cleaned | counts differ | of those: A = source | A = cleaned | B = source | B = cleaned |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for key in ("round 1", "round 2", "rule-3 pool (40)", "both rounds"):
        t = bl[key]
        lines.append(f"| {key} | {t['docs']} | {t['A_src']} | {t['A_cl']} | {t['B_src']} | {t['B_cl']} | {t['differ']} | "
                     f"{t['dA_src']} | {t['dA_cl']} | {t['dB_src']} | {t['dB_cl']} |")

    lines += ["", "## Every study document whose two counts differ", "",
              "`differing_documents.csv`: document, set, split, source count, cleaned count, the counting rules the "
              "cleanup cited (`data/cleanup/COUNTING_RULES.md`) and its reason."]
    (OUT / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    diff = sorted((r for r in rows if r[3] != r[4]), key=lambda r: (SET_ORDER.index(r[1]), r[0]))
    with open(OUT / "differing_documents.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["doc_id", "set", "split", "n_source", "n_cleaned", "status", "rules", "reason"])
        w.writerows(diff)
    print("\n".join(lines))
    print(f"\nwrote {(OUT / 'REPORT.md').relative_to(ROOT)} and {(OUT / 'differing_documents.csv').relative_to(ROOT)} ({len(diff)} documents)")


if __name__ == "__main__":
    main()
